def set_fact(scope: str, key: str, value: str, ref: str = "",
             source: str = "") -> dict:
    """Запоминает факт. scope: user или project. ref - имя проекта."""
    client = _get_client()
    if client is None:
        return {"ok": False, "error": "нет подключения к Supabase"}
    scope = (scope or "user").strip().lower()
    key = (key or "").strip().lower().replace(" ", "_")[:60]
    value = (value or "").strip()[:2000]
    if not key or not value:
        return {"ok": False, "error": "Нужны ключ и значение"}

    ref = slug(ref) if scope == "project" and ref else (ref or "")
    row = {"scope": scope, "ref": ref, "key": key, "value": value,
           "source": (source or "")[:100],
           "updated_at": datetime.now(timezone.utc).isoformat()}
    try:
        upd = (client.table(FACTS).update(row)
               .eq("scope", scope).eq("ref", ref).eq("key", key).execute())
        if getattr(upd, "data", None):
            return {"ok": True, "action": "updated", **row}
        client.table(FACTS).insert(row).execute()
        return {"ok": True, "action": "created", **row}
    except Exception as exc:
        return {"ok": False, "error": f"{type(exc).__name__}: {str(exc)[:200]}"}


def get_facts(scope: str = "user", ref: str = "",
              limit: int = 100) -> list[dict]:
    """Факты по области. scope: all, user или project."""
    client = _get_client()
    if client is None:
        return []
    try:
        q = client.table(FACTS).select("scope, ref, key, value, updated_at")
        if scope != "all":
            q = q.eq("scope", scope)
            if scope == "project" and ref:
                q = q.eq("ref", slug(ref))
        r = q.order("id", desc=False).limit(limit).execute()
        return [{"scope": x.get("scope"), "ref": x.get("ref", ""),
                 "key": x.get("key"), "value": x.get("value"),
                 "updated_at": str(x.get("updated_at", ""))}
                for x in (r.data or [])]
    except Exception:
        return []


def delete_fact(key: str, scope: str = "user", ref: str = "") -> dict:
    client = _get_client()
    if client is None:
        return {"ok": False, "error": "нет подключения к Supabase"}
    try:
        q = (client.table(FACTS).delete()
             .eq("scope", scope).eq("key", key.strip().lower()))
        if scope == "project" and ref:
            q = q.eq("ref", slug(ref))
        r = q.execute()
        if getattr(r, "data", None) is not None:
            return {"ok": True, "deleted": key}
        return {"ok": False, "error": f"Факт «{key}» не найден"}
    except Exception as exc:
        return {"ok": False, "error": f"{type(exc).__name__}: {str(exc)[:200]}"}


def facts_digest(project: str = "") -> str:
    """Готовая строка для системного промпта: что агент помнит."""
    parts: list[str] = []
    user = get_facts("user")
    if user:
        parts.append("О пользователе:\n" + "\n".join(
            f"- {f['key']}: {f['value']}" for f in user))
    if project:
        proj = get_facts("project", project)
        if proj:
            parts.append(f"О проекте «{project}»:\n" + "\n".join(
                f"- {f['key']}: {f['value']}" for f in proj))
    if not parts:
        return ""
    return ("Долговременная память (записана самим агентом, "
            "не выдумана):\n" + "\n\n".join(parts))


