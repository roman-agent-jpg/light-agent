"""Проекты, память о пользователе и журнал действий.

Три сущности, которые делают агента полноценным сервисом, а не
одноразовым чатом:

1. Проекты — у каждого своя изолированная папка и своя переписка.
   Файлы лежат в Storj (S3), список проектов - в Supabase.
   Переключение проекта не требует перезапуска сервера.

2. Факты — долговременная память: кто пользователь, что за проекты,
   предпочтения. Агент читает их в начале разговора и может
   дописывать сам, когда узнаёт новое.

3. Журнал действий — каждая операция агента сохраняется, поэтому
   можно посмотреть, что он делал, даже если чат потерялся.

Всё хранится в Supabase, файлы проектов - в Storj. Схема создаётся
автоматически через Management API (см. ensure_schema).
"""
from __future__ import annotations

import hashlib
import json
import re
from datetime import datetime, timezone

from . import config, storage

_client = None
_unavailable = False

PROJECTS = "agent_projects"
FACTS = "agent_facts"
ACTIONS = "agent_actions"

DEFAULT_PROJECT = "default"

# Имя проекта превращается в безопасный префикс для папки в Storj
_SAFE = re.compile(r"[^a-zA-Z0-9_-]+")


def _get_client():
    global _client, _unavailable
    if _unavailable:
        return None
    if _client is not None:
        return _client
    if not config.memory_enabled():
        _unavailable = True
        return None
    try:
        from supabase import create_client

        _client = create_client(config.SUPABASE_URL, config.SUPABASE_KEY)
        return _client
    except Exception:
        _unavailable = True
        return None


def slug(name: str) -> str:
    """Безопасное имя папки для Storj.

    Нельзя молча сквошить разные имена в один slug: «Мой сайт» и
    «Мой-сайт» стали бы одним проектом, и проекты смешивались бы.
    Поэтому при коллизии добавляем короткий хеш от исходного имени.
    """
    raw = (name or "").strip()
    lowered = raw.lower()

    # Системный проект должен называться ровно "default", без хвоста,
    # иначе пути и проверки в коде начинают расходиться.
    if not raw or lowered == DEFAULT_PROJECT:
        return DEFAULT_PROJECT

    base = _SAFE.sub("-", lowered).strip("-")[:40]
    if not base:
        base = DEFAULT_PROJECT
    # Хвост из хеша сохраняет различимость похожих названий:
    # «Мой сайт» и «Мой-сайт» не должны слиться в один проект.
    tail = hashlib.sha1(raw.encode("utf-8")).hexdigest()[:6]
    return f"{base}-{tail}"


