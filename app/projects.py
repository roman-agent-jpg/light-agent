def log_action(kind: str, tool: str = "", detail: str = "",
               project: str = DEFAULT_PROJECT, session_id: str = "",
               ok: bool = True) -> bool:
    """Записывает действие агента в журнал."""
    client = _get_client()
    if client is None:
        return False
    try:
        client.table(ACTIONS).insert({
            "project": slug(project) if project else DEFAULT_PROJECT,
            "session_id": session_id[:100],
            "kind": kind[:40],
            "tool": tool[:60],
            "detail": (detail or "")[:1500],
            "ok": bool(ok),
        }).execute()
        return True
    except Exception:
        return False


def list_actions(project: str = "", limit: int = 100) -> list[dict]:
    """Журнал действий, свежие сверху."""
    client = _get_client()
    if client is None:
        return []
    try:
        q = client.table(ACTIONS).select(
            "project, session_id, kind, tool, detail, ok, created_at")
        if project:
            q = q.eq("project", slug(project))
        r = q.order("id", desc=True).limit(max(1, min(limit, 500))).execute()
        return [{
            "project": x.get("project"),
            "session_id": x.get("session_id", ""),
            "kind": x.get("kind"),
            "tool": x.get("tool", ""),
            "detail": x.get("detail", ""),
            "ok": x.get("ok", True),
            "created_at": str(x.get("created_at", "")),
        } for x in (r.data or [])]
    except Exception:
        return []


