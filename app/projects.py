def project_prefix(project: str) -> str:
    """Префикс папки проекта в Storj: projects/<slug>/"""
    return f"projects/{slug(project)}"


def list_project_files(project: str, limit: int = 300) -> list[dict]:
    """Файлы проекта в облаке."""
    prefix = project_prefix(project)
    keys = storage.list_keys(prefix)
    out = []
    for k in keys[:limit]:
        rel = k[len(prefix):].lstrip("/")
        if not rel:
            continue
        out.append({"key": k, "path": rel,
                    "is_dir": rel.endswith("/")})
    return out


def status() -> dict:
    """Состояние для /api/status."""
    client = _get_client()
    if client is None:
        return {"enabled": False, "projects": 0, "facts": 0}
    counts = {}
    for name, table in (("projects", PROJECTS), ("facts", FACTS),
                        ("actions", ACTIONS)):
        try:
            r = client.table(table).select("id", count="exact").execute()
            counts[name] = r.count or 0
        except Exception:
            counts[name] = 0
    return {"enabled": True, **counts}