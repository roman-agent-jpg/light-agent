def create_project(name: str, description: str = "") -> dict:
    """Создаёт проект и папку для его файлов.

    Повторный вызов с тем же именем обновляет описание, а не создаёт дубль.
    """
    name = (name or "").strip()
    if not name:
        return {"ok": False, "error": "Имя проекта пустое"}

    s = slug(name)
    # Физически создаём папку проекта в workspace
    p_dir = config.project_dir(s)

    client = _get_client()
    if client is None:
        # Локальный режим без Supabase
        return {
            "ok": True,
            "action": "created",
            "name": name,
            "slug": s,
            "description": description,
            "local": True,
            "path": str(p_dir),
        }

    # Ищем по имени: переименование меняет slug, а имя остаётся ключом
    existing = get_project(name)
    if existing:
        try:
            patch = {"updated_at": datetime.now(timezone.utc).isoformat()}
            if description:
                patch["description"] = description.strip()[:500]
            (client.table(PROJECTS).update(patch)
             .eq("slug", existing["slug"]).execute())
            return {"ok": True, "action": "updated", "name": name,
                    "slug": existing["slug"], "path": str(p_dir)}
        except Exception as exc:
            return {"ok": False,
                    "error": f"{type(exc).__name__}: {str(exc)[:200]}"}

    row = {
        "name": name,
        "slug": s,
        "description": (description or "").strip()[:500],
        "updated_at": datetime.now(timezone.utc).isoformat(),
    }
    try:
        client.table(PROJECTS).insert(row).execute()
        return {"ok": True, "action": "created", **row, "path": str(p_dir)}
    except Exception as exc:
        return {"ok": False, "error": f"{type(exc).__name__}: {str(exc)[:200]}"}


def _count_files(s: str) -> int:
    d = config.WORKSPACE / s
    if not d.is_dir():
        return 0
    try:
        return sum(1 for p in d.rglob("*") if p.is_file() and not any(part.startswith(".") for part in p.parts))
    except Exception:
        return 0


def list_projects() -> list[dict]:
    """Все проекты, объединённые из Supabase и локальной папки workspace."""
    client = _get_client()
    seen_slugs = set()
    out = []

    if client is not None:
        try:
            r = (client.table(PROJECTS)
                 .select("name, slug, description, updated_at, created_at")
                 .order("updated_at", desc=True)
                 .execute())
            for row in (r.data or []):
                s = row.get("slug")
                if s:
                    seen_slugs.add(s)
                    out.append({
                        "name": row.get("name") or s,
                        "slug": s,
                        "description": row.get("description") or "",
                        "updated_at": str(row.get("updated_at", "")),
                        "created_at": str(row.get("created_at", "")),
                        "files": _count_files(s),
                    })
        except Exception:
            pass

    # Всегда гарантируем наличие default проекта
    if "default" not in seen_slugs:
        config.project_dir("default")
        out.insert(0, {
            "name": "default",
            "slug": "default",
            "description": "Основной проект",
            "updated_at": datetime.now(timezone.utc).isoformat(),
            "created_at": datetime.now(timezone.utc).isoformat(),
            "files": _count_files("default"),
        })
        seen_slugs.add("default")

    # Добавляем локальные папки из workspace, если их ещё нет в Supabase
    try:
        for entry in config.WORKSPACE.iterdir():
            if entry.is_dir() and not entry.name.startswith("."):
                s = entry.name
                if s not in seen_slugs:
                    seen_slugs.add(s)
                    out.append({
                        "name": s,
                        "slug": s,
                        "description": "Локальная папка проекта",
                        "updated_at": datetime.fromtimestamp(entry.stat().st_mtime, timezone.utc).isoformat(),
                        "created_at": datetime.fromtimestamp(entry.stat().st_ctime, timezone.utc).isoformat(),
                        "files": _count_files(s),
                    })
    except Exception:
        pass

    return out


def get_project(name: str) -> dict | None:
    """Один проект по имени или slug."""
    s = slug(name)
    for p in list_projects():
        if p["slug"] == s or p["name"].lower() == (name or "").lower():
            return p
    return None


def delete_project(name: str) -> dict:
    """Удаляет проект. Файлы в Storj НЕ трогаются."""
    client = _get_client()
    if client is None:
        return {"ok": False, "error": "нет подключения к Supabase"}
    s = slug(name)
    try:
        r = client.table(PROJECTS).delete().eq("slug", s).execute()
        if getattr(r, "data", None):
            return {"ok": True, "deleted": s,
                    "note": "Файлы проекта в облаке остались нетронутыми"}
        return {"ok": False, "error": f"Проект «{name}» не найден"}
    except Exception as exc:
        return {"ok": False, "error": f"{type(exc).__name__}: {str(exc)[:200]}"}


def ensure_default() -> dict:
    """Гарантирует, что есть проект default - иначе работать не с чем."""
    if get_project(DEFAULT_PROJECT):
        return get_project(DEFAULT_PROJECT)
    res = create_project(
        DEFAULT_PROJECT, "Основной проект: файлы и переписка")
    return res if res.get("ok") else {"name": DEFAULT_PROJECT,
                                       "slug": DEFAULT_PROJECT}


