DDL = f"""
create table if not exists {PROJECTS} (
    id bigint generated by default as identity primary key,
    name text not null unique,
    slug text not null unique,
    description text default '',
    created_at timestamptz default now(),
    updated_at timestamptz default now()
);

create table if not exists {FACTS} (
    id bigint generated by default as identity primary key,
    scope text not null default 'user',
    ref text not null default '',
    key text not null,
    value text not null,
    source text default '',
    created_at timestamptz default now(),
    updated_at timestamptz default now()
);
create unique index if not exists agent_facts_uniq
    on {FACTS}(scope, ref, key);

create table if not exists {ACTIONS} (
    id bigint generated by default as identity primary key,
    project text not null default 'default',
    session_id text default '',
    kind text not null,
    tool text default '',
    detail text default '',
    ok boolean default true,
    created_at timestamptz default now()
);
create index if not exists agent_actions_proj
    on {ACTIONS}(project, id desc);
"""


def ensure_schema() -> dict:
    """Создаёт все таблицы. Работает через Management API."""
    client = _get_client()
    if client is None:
        return {"ok": False, "reason": "нет подключения к Supabase"}

    token = config.SUPABASE_ACCESS_TOKEN
    ref = config.SUPABASE_PROJECT_REF
    if token and ref:
        try:
            import httpx

            r = httpx.post(
                f"https://api.supabase.com/v1/projects/{ref}/database/query",
                headers={"Authorization": f"Bearer {token}",
                         "Content-Type": "application/json"},
                json={"query": DDL},
                timeout=60.0,
            )
            if r.status_code < 300:
                return {"ok": True, "method": "management_api"}
            detail = r.text[:200]
        except Exception as exc:
            detail = f"{type(exc).__name__}: {exc}"

        try:
            client.table(PROJECTS).select("name").limit(1).execute()
            return {"ok": True, "method": "already_exists",
                    "note": f"Management API: {detail}"}
        except Exception:
            return {"ok": False, "reason": detail}

    # Без токена только проверяем доступ
    try:
        client.table(PROJECTS).select("name").limit(1).execute()
        return {"ok": True, "method": "already_exists"}
    except Exception as exc:
        return {"ok": False, "reason": f"{type(exc).__name__}: {str(exc)[:150]}"}


