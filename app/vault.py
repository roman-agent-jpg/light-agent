DDL = """
create table if not exists agent_secrets (
    id bigint generated by default as identity primary key,
    name text not null unique,
    value text not null,
    note text,
    created_at timestamptz default now(),
    updated_at timestamptz default now()
);
create index if not exists agent_secrets_name_idx on agent_secrets(name);
"""


def ensure_table() -> dict:
    """Создаёт таблицу, если её нет.

    Python-клиент supabase не умеет DDL. Поэтому идём через
    Management API — но только если задан SUPABASE_ACCESS_TOKEN.
    Без токена проверяем простым SELECT: возможно, таблицу создали
    вручную через SQL Editor.
    """
    client = _get_client()
    if client is None:
        return {"ok": False, "reason": "нет подключения к Supabase"}

    # 1. Пробуем Management API — он умеет DDL
    token = config.SUPABASE_ACCESS_TOKEN
    ref = config.SUPABASE_PROJECT_REF
    if token and ref:
        try:
            import httpx

            r = httpx.post(
                f"https://api.supabase.com/v1/projects/{ref}/database/query",
                headers={"Authorization": f"Bearer {token}",
                         "Content-Type": "application/json"},
                json={"query": DDL},
                timeout=45.0,
            )
            if r.status_code < 300:
                return {"ok": True, "method": "management_api"}
            detail = r.text[:200]
        except Exception as exc:
            detail = f"{type(exc).__name__}: {exc}"

        # 2. Management API не сработал — возможно, таблица уже есть
        try:
            client.table(SECRETS_TABLE).select("name").limit(1).execute()
            return {"ok": True, "method": "already_exists",
                    "note": f"Management API: {detail}"}
        except Exception:
            return {"ok": False, "method": "management_api",
                    "reason": detail}
    else:
        # Токена нет — только проверяем доступ
        try:
            client.table(SECRETS_TABLE).select("name").limit(1).execute()
            return {"ok": True, "method": "already_exists"}
        except Exception as exc:
            return {"ok": False, "method": "select",
                    "reason": f"{type(exc).__name__}: {str(exc)[:200]}"}


