# Шифрование
# ---------------------------------------------------------------------------

def _fernet():
    """Fernet с ключом, выведенным из ADMIN_TOKEN.

    Хеш SHA-256 даёт ровно 32 байта — это и есть требуемая длина
    ключа Fernet (base64url от 32 байт). Так мастер-ключ один,
    а шифротекст можно хранить в базе как есть.
    """
    from cryptography.fernet import Fernet

    token = config.ADMIN_TOKEN
    if not token or token == "dev-token":
        raise RuntimeError(
            "ADMIN_TOKEN не настроен: без него нельзя шифровать секреты")
    digest = hashlib.sha256(token.encode("utf-8")).digest()
    return Fernet(base64.urlsafe_b64encode(digest))


def encrypt(value: str) -> str:
    """Шифрует строку, возвращает base64-текст для хранения в базе."""
    return _fernet().encrypt(value.encode("utf-8")).decode("ascii")


def decrypt(ciphertext: str) -> str:
    """Расшифровывает значение из базы."""
    return _fernet().decrypt(ciphertext.encode("ascii")).decode("utf-8")


