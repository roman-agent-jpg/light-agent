"""Хранилище секретов: шифрованное, вне рабочей папки проекта.

Зачем это нужно
---------------
Агенту нужны ключи (Render API Token, GitHub Token), чтобы управлять
инфраструктурой. Но если положить их в .env проекта или в файл рядом
с кодом, они уедут в git при первом же пуше.

Решение: секреты лежат в Supabase, зашифрованные алгоритмом Fernet
(симметричное шифрование из библиотеки cryptography). Ключ шифрования
выводится из ADMIN_TOKEN, который уже есть на сервере Render и в
переменных окружения — то есть мастер-ключ никогда не хранится рядом
с данными и не попадает в репозиторий.

Что это НЕ делает
-----------------
Это не защита от владельца сервера — он и так имеет доступ. Это защита
от случайной утечки: ключ нельзя прочитать из файлов проекта, нельзя
закоммитить, нельзя увидеть в логах агента.
"""
from __future__ import annotations

import base64
import hashlib
import json
from datetime import datetime, timezone

from . import config

_client = None
_unavailable = False

SECRETS_TABLE = "agent_secrets"

# Префиксы ключей, которые хранить можно. Всё остальное отклоняется,
# чтобы агент случайно не засунул в базу мусор.
# AGENT_ тоже разрешён: модели естественно называть «AGENT_API_KEY»,
# и без этого префикса агент путается и подставляет другие имена.
ALLOWED_PREFIXES = (
    "RENDER_", "GITHUB_", "VERCEL_", "AWS_", "SUPABASE_",
    "OPENROUTER_", "GROQ_", "GEMINI_", "AG_", "AGENT_",
    "ANTHROPIC_", "DB_", "API_",
)

# Явный запрет: эти имена нельзя перезаписывать, иначе агент
# может сломать собственное хранилище или авторизацию.
PROTECTED = ("ADMIN_TOKEN", "SUPABASE_KEY", "SUPABASE_URL")


def _get_client():
    """Клиент Supabase. Общий с memory.py, но держим свой."""
    global _client, _unavailable
    if _unavailable:
        return None
    if _client is not None:
        return _client
    if not config.memory_enabled():
        _unavailable = True
        return None
    try:
        from supabase import create_client

        _client = create_client(config.SUPABASE_URL, config.SUPABASE_KEY)
        return _client
    except Exception:
        _unavailable = True
        return None


